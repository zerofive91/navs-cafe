export const TRIALS = []; // 모든 문항 (숲길 길별 + common + 훈련소 장면)
const OWN = {}; // 길 id → 그 길의 문항
for (const [path, list] of Object.entries(PATHS)) {
  OWN[path] = list;
  for (const T of list) { T.path = path; T.src = 'dg'; T.village = T.village || 'base'; TRIALS.push(T); }
}
for (const T of SCENES) { T.path = null; T.src = 'wf'; T.village = 'base'; VERSES['wf-' + T.id] = T.a; TRIALS.push(T); }
export const BY = Object.fromEntries(TRIALS.map((T) => [T.id, T]));
export { SCENES };
export const kindOf = (T) => T.kind || 'pick';
export const vkey = (T) => T.v || (T.src === 'wf' ? 'wf-' : 'dg-') + T.id; // 말씀 키 (verses.js)
export const verseOf = (id) => VERSES[vkey(BY[id])]; // [개역한글, 장절]
const campable = (T) => kindOf(T) === 'pick' && T.no?.length === 2 && !!T.win && T.path !== 'common';
// 이 문항이 나오는 자리 (검증·표용)
export function where(T) {
  const out = [];
  if (T.path && T.path !== 'common') out.push(T.big ? 'forest-big:' + T.path : 'forest-small:' + T.path);
  if (T.path === 'common') out.push(T.big ? 'forest-big:common' : 'forest-small:common');
  for (const p of T.paths || []) out.push('forest-small:' + p);
  if (campable(T)) out.push(T.scene ? 'camp-scene' : 'camp-forest');
  return out;
}
// 시험 세트 (마을 등록부·다른 모듈이 id로 참조): { 세트 id: { village, at: 'forest' 숲길 길 | 'camp' 훈련소 | 'any' 떠도는 속삭임, n: 문항 수 } }
//   숲길 세트 id = 길 id (layout.js TRAILS, dungeon.js TIER). pool(at, { path: 세트 id })로 그 세트의 문항을 꺼냄
export const TRIAL_SETS = Object.freeze(Object.fromEntries([
  ...Object.entries(PATHS).map(([id, list]) => [id, Object.freeze({ village: 'base', at: id === 'common' ? 'any' : 'forest', n: list.length })]),
  ['camp', Object.freeze({ village: 'base', at: 'camp', n: TRIALS.filter((T) => campable(T)).length })],
  // 묶음: 마을 등록부 trialSet 'forest'(js/villages/base.js)가 가리키는 초보자 마을 숲길 15길 전체
  ['forest', Object.freeze({ village: 'base', at: 'forest', sets: Object.freeze(Object.keys(PATHS).filter((id) => id !== 'common')),
    n: Object.entries(PATHS).reduce((a, [id, l]) => a + (id === 'common' ? 0 : l.length), 0) })],
]));
export const setsOf = (village) => Object.keys(TRIAL_SETS).filter((id) => TRIAL_SETS[id].village === village);

// 상황별 문항 목록
//   'small' 숲길 작은 시험 { path, tier } · 'big' 숲길 큰 시험 { path } · 'camp' 훈련소 { cat(없으면 전부), scene: true 장면만 / false 숲길 문항만 }
export function pool(at, { path, tier = 3, cat = null, scene = null } = {}) {
  if (at === 'big') return (OWN[path] || []).filter((T) => T.big);
  if (at === 'small') return [...(OWN[path] || []).filter((T) => !T.big), ...SCENES.filter((T) => T.paths?.includes(path) && (T.tier || 2) <= tier)];
  if (at === 'camp') return TRIALS.filter((T) => campable(T) && (!cat || T.cat === cat) && (scene == null || !!T.scene === scene));
  return [];
}

// ---------- 최근 본 문항: 이 기기에만 { 자리: [가장 최근 id, ...] } (계정에 올리지 않음, 못 쓰면 이번만) ----------
//   자리 = 길 id(숲길, PR #52부터 같은 칸) · 'camp'(훈련소) · '_all'(어디서든 최근 본 것)
const SEEN_KEY = 'navs-cafe-dg-seen';
let seen = {};
try { seen = JSON.parse(localStorage.getItem(SEEN_KEY) || '{}') || {}; } catch (e) { seen = {}; }
const recent = (key) => (Array.isArray(seen[key]) ? seen[key] : []);
export function markSeen(key, id) {
  for (const [k, n] of [[key, 12], ['_all', 16]]) seen[k] = [id, ...recent(k).filter((x) => x !== id)].slice(0, n);
  try { localStorage.setItem(SEEN_KEY, JSON.stringify(seen)); } catch (e) { /* 이번만 */ }
}
// 같은 길을 다시 이긴 보상 상한: 길마다 하루(이 기기 날짜) 첫 번째만 true. 이 기기에만 { d: 'YYYY-MM-DD', p: [길 id…] } (계정에 올리지 않음)
const REDO_KEY = 'navs-cafe-dg-redo';
export function firstRedoToday(path, now = new Date()) {
  const pad = (n) => String(n).padStart(2, '0');
  const d = `${now.getFullYear()}-${pad(now.getMonth() + 1)}-${pad(now.getDate())}`;
  let r = null;
  try { r = JSON.parse(localStorage.getItem(REDO_KEY) || 'null'); } catch (e) { r = null; }
  if (!r || r.d !== d || !Array.isArray(r.p)) r = { d, p: [] };
  if (r.p.includes(path)) return false;
  r.p.push(path);
  try { localStorage.setItem(REDO_KEY, JSON.stringify(r)); } catch (e) { /* 이번만 */ }
  return true;
}
// 목록에서 n개 고르기: avoid(이번 걸음에 이미 나온 id) → 그 자리에서 안 본 것 먼저, 본 것은 오래전 것부터 → 어디서든 최근 본 것 뒤로 → 나머지는 무작위
export function draw(list, key, { n = 1, avoid = [], rnd = Math.random } = {}) {
  const mine = recent(key), all = recent('_all');
  const age = (arr, id) => { const i = arr.indexOf(id); return i < 0 ? 0 : arr.length - i; };
  return list.map((T) => [T, avoid.includes(T.id) ? 1 : 0, age(mine, T.id), age(all, T.id), rnd()])
    .sort((a, b) => a[1] - b[1] || a[2] - b[2] || a[3] - b[3] || a[4] - b[4])
    .slice(0, n).map((x) => x[0]);
}
