import { STREAMS } from './wordstream.js';

const el = () => document.getElementById('verse');
const last = {};
let hideT = 0;
// 이어지는 구절: 카드를 눌러야 다음 구절이 뜸 (저절로 연달아 넘어가지 않게)
let queue = null; // { keys, title, stay }
function fadeOut(e) {
  e.classList.remove('on', 'more');
  hideT = setTimeout(() => { e.hidden = true; }, 1600);
}
function render(key, title) {
  const v = VERSES[key];
  const e = el();
  if (!v || !e) return;
  e.querySelector('p').textContent = v[0];
  e.querySelector('cite').textContent = v[1];
  setTitle(e, title);
  e.hidden = false;
  e.classList.toggle('more', !!(queue && queue.keys.length));
  requestAnimationFrame(() => e.classList.add('on'));
  clearTimeout(hideT);
  const ms = 6500 + v[0].length * 40;
  const born = performance.now();
  const check = () => {
    // 다음 구절이 남아 있으면 자리를 떠나거나(stay) 1분이 지날 때까지 기다림
    if (queue && queue.keys.length && (!queue.stay || queue.stay()) && performance.now() - born < 60000) { hideT = setTimeout(check, 1000); return; }
    queue = null;
    fadeOut(e);
  };
  hideT = setTimeout(check, ms);
}
export function showVerse(key, { delay = 0, cooldown = 90, title = '', then = null, stay = null } = {}) {
  const v = VERSES[key];
  if (!v) return false;
  const now = performance.now() / 1000;
  if (last[key] && now - last[key] < cooldown) return false;
  last[key] = now;
  setTimeout(() => {
    queue = then && then.length ? { keys: then.filter((k) => VERSES[k]), title, stay } : null;
    render(key, title);
  }, delay * 1000);
  return true;
}
function tapNext(ev) {
  ev.stopPropagation();
  ev.preventDefault();
  nextVerse();
}
// 다음 구절로 (카드를 누르거나 Enter 키)
export function nextVerse() {
  if (!queue || !queue.keys.length) return;
  const e = el();
  const k = queue.keys.shift();
  last[k] = performance.now() / 1000;
  e.classList.remove('on');
  clearTimeout(hideT);
  hideT = setTimeout(() => render(k, queue ? queue.title : ''), 450);
}
document.addEventListener('pointerdown', (ev) => { if (ev.target.closest?.('#verse.more')) tapNext(ev); }, true);

// 이어지는 말씀: 버튼을 누른 동안 한 구절씩 차례로(겹치지 않게 섞어서) 계속 띄움
let stream = null;
const decks = {};
function nextOf(kind) {
  if (!decks[kind] || !decks[kind].length) decks[kind] = [...STREAMS[kind]].sort(() => Math.random() - 0.5);
  return decks[kind].pop();
}
// 구절 위에 작은 이름(상징 이름 등)
function setTitle(e, title) {
  let t = e.querySelector('.vt');
  if (!t) { t = document.createElement('b'); t.className = 'vt'; e.prepend(t); }
  t.textContent = title || '';
  t.hidden = !title;
}
function showPair(v) {
  const e = el();
  if (!e) return 0;
  setTitle(e, '');
  e.querySelector('p').textContent = v[0];
  e.querySelector('cite').textContent = v[1];
  e.hidden = false;
  e.classList.remove('more');
  requestAnimationFrame(() => e.classList.add('on'));
  return 6500 + v[0].length * 45;
}
export function startStream(kind, delay = 1.2) {
  if (stream && stream.kind === kind) return;
  queue = null;
  stopStream(true);
  const s = { kind, t: 0 };
  stream = s;
  const tick = () => {
    if (stream !== s) return;
    clearTimeout(hideT);
    const ms = showPair(nextOf(kind));
    s.t = setTimeout(() => {
      if (stream !== s) return;
      el().classList.remove('on');
      s.t = setTimeout(tick, 1700); // 사라진 뒤 잠시 쉬고 다음 구절
    }, ms);
  };
  s.t = setTimeout(tick, delay * 1000);
}
export function stopStream(quick) {
  if (!stream) return;
  clearTimeout(stream.t);
  stream = null;
  const e = el();
  if (e && quick) e.classList.remove('on');
  else if (e) hideT = setTimeout(() => e.classList.remove('on'), 2500);
}

// 버튼을 누를 때마다 한 구절 (같은 구절은 목록을 다 돌 때까지 반복하지 않음)
export function showNext(kind, delay = 0.6) {
  stopStream(true);
  queue = null;
  setTimeout(() => {
    const ms = showPair(nextOf(kind));
    clearTimeout(hideT);
    hideT = setTimeout(() => {
      const e = el();
      e.classList.remove('on');
      hideT = setTimeout(() => { e.hidden = true; }, 1600);
    }, ms);
  }, delay * 1000);
}
